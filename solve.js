// A fast drop-in for makefun-site 1.0.0: build(input) turns one site's sources into its
// output tree, a JSON object of path -> text, byte for byte what makefun-site returns.
// Written from the makefun-site README's rules. Same pipeline, same order, same answers;
// the work is done with tight single-pass scanners instead of the reference's regexes
// and per-character calls, so the same output costs far less CPU.

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const RESERVED = ['posts', 'tags', 'page'];

// ---------------------------------------------------------------- text

/** `s` with & < > " ' escaped, appended to `out` (as one chunk when nothing escapes). */
const ESC_RE = /[&<>"']/g;
function escapeRange(s, lo, hi, out) {
  let i = lo;
  ESC_RE.lastIndex = lo;
  for (;;) {
    const m = ESC_RE.exec(s);
    const j = m === null || m.index >= hi ? -1 : m.index;
    if (j === -1) {
      if (i < hi) out.push(s.slice(i, hi));
      ESC_RE.lastIndex = 0;
      return;
    }
    if (j > i) out.push(s.slice(i, j));
    const c = s.charCodeAt(j);
    out.push(c === 38 ? '&amp;' : c === 60 ? '&lt;' : c === 62 ? '&gt;' : c === 34 ? '&quot;' : '&#39;');
    i = j + 1;
    ESC_RE.lastIndex = i;
  }
}

/** `s` with & < > " ' escaped. */
const ESC_TEST = /[&<>"']/;
/** Escaped template values, memoised: the same titles and urls are written on every page. */
const escCache = new Map();
function escapeHtml(s) {
  let e = escCache.get(s);
  if (e !== undefined) return e;
  if (!ESC_TEST.test(s)) {
    escCache.set(s, s);
    return s;
  }
  const out = [];
  escapeRange(s, 0, s.length, out);
  e = out.join('');
  escCache.set(s, e);
  return e;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

/** The most characters a slug keeps before a collision suffix. */
const SLUG_MAX = 64;

/** Memoised slugs: titles and tag names repeat across a site. */
const slugCache = new Map();

/** The slug of `text`: NFKD, combining marks dropped, A-Z lowered, every run of characters
 *  other than a-z and 0-9 one "-", none at either end, at most 64 characters (a "-" left at
 *  the cut dropped), and "untitled" when nothing is left. */
function slugify(text) {
  const hit = slugCache.get(text);
  if (hit !== undefined) return hit;
  let plain = text;
  let ascii = true;
  for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) > 127) { ascii = false; break; }
  if (!ascii) plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length && out.length < SLUG_MAX; i++) {
    const c = plain.charCodeAt(i);
    let keep = 0;
    if (c >= 65 && c <= 90) keep = c + 32;
    else if ((c >= 97 && c <= 122) || (c >= 48 && c <= 57)) keep = c;
    if (keep === 0) {
      gap = out.length > 0;
      continue;
    }
    if (gap) {
      if (out.length === SLUG_MAX) break;
      out += '-';
    }
    gap = false;
    out += String.fromCharCode(keep);
  }
  let end = out.length;
  while (end > 0 && out.charCodeAt(end - 1) === 45) end--;
  const result = end === 0 ? 'untitled' : end === out.length ? out : out.slice(0, end);
  slugCache.set(text, result);
  return result;
}

/** `slug` made unique against `taken` (and added to it): slug, slug-2, slug-3 ... */
function uniqueSlug(slug, taken) {
  if (!taken.has(slug)) {
    taken.add(slug);
    return slug;
  }
  let n = 2;
  let out = `${slug}-2`;
  while (taken.has(out)) out = `${slug}-${++n}`;
  taken.add(out);
  return out;
}

// ---------------------------------------------------------------- front matter

const KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

/** A string with trailing spaces and tabs dropped. */
function stripTrailingST(s) {
  let e = s.length;
  while (e > 0) {
    const c = s.charCodeAt(e - 1);
    if (c === 32 || c === 9) e--;
    else break;
  }
  return e === s.length ? s : s.slice(0, e);
}

/** True when every character of `line` is a space or a tab (the empty line included). */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** The days of month `m` (1-12) of year `y`, by the Gregorian rule. */
function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

/** A string value: "..." with \" and \\ its only escapes, or bare, the rest of the line. */
function stringOf(raw) {
  if (raw.charCodeAt(0) === 34) {
    if (raw.length < 2 || raw.charCodeAt(raw.length - 1) !== 34) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.charCodeAt(0) === 91) return { error: 'a bare string opens on [' };
  return { value: raw };
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      if (raw.length !== 10 || raw.charCodeAt(4) !== 45 || raw.charCodeAt(7) !== 45) {
        return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      }
      for (const k of [0, 1, 2, 3, 5, 6, 8, 9]) {
        const c = raw.charCodeAt(k);
        if (c < 48 || c > 57) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      }
      const y = (raw.charCodeAt(0) - 48) * 1000 + (raw.charCodeAt(1) - 48) * 100 + (raw.charCodeAt(2) - 48) * 10 + (raw.charCodeAt(3) - 48);
      const mo = (raw.charCodeAt(5) - 48) * 10 + (raw.charCodeAt(6) - 48);
      const d = (raw.charCodeAt(8) - 48) * 10 + (raw.charCodeAt(9) - 48);
      if (y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) {
        return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      }
      return { value: raw };
    }
    case 'tags': {
      if (raw.charCodeAt(0) !== 91 || raw.charCodeAt(raw.length - 1) !== 93) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '' || t.indexOf('"') !== -1 || t.indexOf('[') !== -1 || t.indexOf(']') !== -1) {
          return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      if (raw.length === 0) return { error: 'key "layout": not a template name' };
      for (let i = 0; i < raw.length; i++) {
        const c = raw.charCodeAt(i);
        if (!((c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 45)) return { error: 'key "layout": not a template name' };
      }
      return { value: raw };
    }
    case 'slug': {
      if (raw.length === 0 || raw.length > 64) return { error: 'key "slug": not a slug' };
      let prevDash = true;
      for (let i = 0; i < raw.length; i++) {
        const c = raw.charCodeAt(i);
        if ((c >= 97 && c <= 122) || (c >= 48 && c <= 57)) { prevDash = false; continue; }
        if (c === 45 && !prevDash) { prevDash = true; continue; }
        return { error: 'key "slug": not a slug' };
      }
      if (prevDash) return { error: 'key "slug": not a slug' };
      return { value: raw };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/**
 * A source's front matter and body: { data, body }, or { error } with the first reason it is
 * refused. `text` has "\n" line ends.
 */
function parseFrontMatter(text) {
  if (text.length < 3 || text.charCodeAt(0) !== 45 || text.charCodeAt(1) !== 45 || text.charCodeAt(2) !== 45) return { error: 'no front matter' };
  if (text.length > 3 && text.charCodeAt(3) !== 10) return { error: 'no front matter' };
  const data = {};
  let i = 4;
  let lineNo = 2;
  for (;;) {
    if (i > text.length) return { error: 'the front matter is not closed' };
    let j = text.indexOf('\n', i);
    if (j === -1) j = text.length;
    const line = text.slice(i, j);
    if (line === '---') {
      if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
      return { data, body: j === text.length ? '' : text.slice(j + 1) };
    }
    if (line !== '' && line.charCodeAt(0) !== 35 && !isBlank(line)) {
      const colon = line.indexOf(':');
      if (colon <= 0) return { error: `line ${lineNo} is not "key: value"` };
      const key = line.slice(0, colon);
      for (let k = 0; k < key.length; k++) {
        const c = key.charCodeAt(k);
        if (!((c >= 97 && c <= 122) || c === 95)) return { error: `line ${lineNo} is not "key: value"` };
      }
      let raw;
      if (colon === line.length - 1) raw = '';
      else if (line.charCodeAt(colon + 1) === 32) raw = line.slice(colon + 2);
      else return { error: `line ${lineNo} is not "key: value"` };
      raw = stripTrailingST(raw);
      if (!KEYS.has(key)) return { error: `unknown key "${key}"` };
      if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
      if (raw === '') return { error: `key "${key}" has no value` };
      const v = valueOf(key, raw);
      if ('error' in v) return v;
      data[key] = v.value;
    }
    if (j === text.length) return { error: 'the front matter is not closed' };
    i = j + 1;
    lineNo++;
  }
}

// ---------------------------------------------------------------- markdown

/** `line` with spaces and tabs at either end dropped. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/** The language of a fence-opening line, "" for a bare fence, or null when it is not one. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) i++;
    else break;
  }
  for (let k = i; k < line.length; k++) {
    const c = line.charCodeAt(k);
    if (c !== 32 && c !== 9) return null;
  }
  return line.slice(3, i);
}

/** True when `line` closes a fence: three backticks, then spaces or tabs only. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let k = 3; k < line.length; k++) {
    const c = line.charCodeAt(k);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  if (line.charCodeAt(0) !== 35) return null;
  let h = 0;
  while (h < 6 && line.charCodeAt(h) === 35) h++;
  if (h >= line.length) return null;
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  let s = h;
  while (s < line.length && (line.charCodeAt(s) === 32 || line.charCodeAt(s) === 9)) s++;
  const text = stripTrailingST(line.slice(s));
  return text === '' ? null : { depth: h, text };
}

/** True when `line` is a thematic break: `---` or `***`, then spaces or tabs only. */
function isHr(line) {
  if (line.length < 3) return false;
  const a = line.charCodeAt(0);
  const b = line.charCodeAt(1);
  const c = line.charCodeAt(2);
  if (!((a === 45 && b === 45 && c === 45) || (a === 42 && b === 42 && c === 42))) return false;
  for (let k = 3; k < line.length; k++) {
    const ch = line.charCodeAt(k);
    if (ch !== 32 && ch !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceLang(line) !== null || headingOf(line) !== null || isHr(line);
}

/** True when `c` is JavaScript whitespace (what /\s/ matches). */
function isWSCode(c) {
  if (c > 32 && c < 0xA0) return false;
  return c === 32 || (c >= 9 && c <= 13) || c === 0xA0 || c === 0x1680 || (c >= 0x2000 && c <= 0x200A) ||
    c === 0x2028 || c === 0x2029 || c === 0x202F || c === 0x205F || c === 0x3000 || c === 0xFEFF;
}

/** A bullet item's text after "- " or "* ", or null. */
function bulletText(line) {
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** An ordered item's { num, text } after "N. ", or null (at most 9 digits). */
function orderedItem(line) {
  let i = 0;
  while (i < 9 && line.charCodeAt(i) >= 48 && line.charCodeAt(i) <= 57) i++;
  if (i === 0) return null;
  if (line.charCodeAt(i) !== 46 || line.charCodeAt(i + 1) !== 32) return null;
  let num = 0;
  for (let k = 0; k < i; k++) num = num * 10 + (line.charCodeAt(k) - 48);
  return { num, text: line.slice(i + 2) };
}

/** True when `line` continues a list item: two or more spaces, then a non-space. */
function isContinued(line) {
  if (line.charCodeAt(0) !== 32 || line.charCodeAt(1) !== 32) return false;
  let i = 2;
  while (i < line.length && line.charCodeAt(i) === 32) i++;
  return i < line.length && !isWSCode(line.charCodeAt(i));
}

/** The characters a backslash escapes, by code (0-127). */
const ESCAPABLE = new Uint8Array(128);
for (const ch of ['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']) ESCAPABLE[ch.charCodeAt(0)] = 1;

/** The first index from `from` (under `hi`) where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from, hi) {
  const w0 = what.charCodeAt(0);
  const w1 = what.length === 2 ? what.charCodeAt(1) : -1;
  for (let j = from; j <= hi - what.length; j++) {
    if (s.charCodeAt(j) === 92 && j + 1 < hi && ESCAPABLE[s.charCodeAt(j + 1)] === 1) {
      j++;
      continue;
    }
    if (s.charCodeAt(j) === w0 && (w1 === -1 || s.charCodeAt(j + 1) === w1)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, hi) {
  for (let j = from; j < hi; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < hi && ESCAPABLE[s.charCodeAt(j + 1)] === 1) {
      j++;
      continue;
    }
    if (c !== 42) continue;
    if (j + 1 < hi && s.charCodeAt(j + 1) === 42) {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

const HAS_WS = /\s/;

/** The characters inline rendering treats specially: \ ` * [ and the escape table's. */
const SPECIAL_RE = /[\\`*\[&<>"']/g;

/** `s[lo..hi)` rendered inline, appended to `out`; `env.link(target)` is a link's href. */
function inlineRange(s, lo, hi, env, out) {
  let i = lo;
  SPECIAL_RE.lastIndex = lo;
  for (;;) {
    const m = SPECIAL_RE.exec(s);
    const j = m === null || m.index >= hi ? -1 : m.index;
    if (j === -1) {
      if (i < hi) out.push(s.slice(i, hi));
      return;
    }
    if (j > i) out.push(s.slice(i, j));
    const c = s.charCodeAt(j);
    if (c === 92) {
      if (j + 1 < hi && ESCAPABLE[s.charCodeAt(j + 1)] === 1) {
        const n = s[j + 1];
        out.push(n === '>' ? '&gt;' : n);
        i = j + 2;
      } else {
        out.push('\\');
        i = j + 1;
      }
    } else if (c === 96) {
      const k = s.indexOf('`', j + 1);
      if (k !== -1 && k < hi && k > j + 1) {
        out.push('<code>');
        escapeRange(s, j + 1, k, out);
        out.push('</code>');
        i = k + 1;
      } else {
        out.push('`');
        i = j + 1;
      }
    } else if (c === 42) {
      if (j + 1 < hi && s.charCodeAt(j + 1) === 42) {
        const k = findUnescaped(s, '**', j + 2, hi);
        if (k > j + 2) {
          out.push('<strong>');
          inlineRange(s, j + 2, k, env, out);
          out.push('</strong>');
          i = k + 2;
        } else {
          out.push('**');
          i = j + 2;
        }
      } else {
        const k = findSingleStar(s, j + 1, hi);
        if (k > j + 1) {
          out.push('<em>');
          inlineRange(s, j + 1, k, env, out);
          out.push('</em>');
          i = k + 1;
        } else {
          out.push('*');
          i = j + 1;
        }
      }
    } else if (c === 91) {
      const k = findUnescaped(s, ']', j + 1, hi);
      let mm = -1;
      if (k !== -1 && k + 1 < hi && s.charCodeAt(k + 1) === 40) {
        mm = s.indexOf(')', k + 2);
        if (mm === -1 || mm >= hi) mm = -1;
      }
      if (mm !== -1) {
        const target = s.slice(k + 2, mm);
        if (target !== '' && !HAS_WS.test(target)) {
          const href = env.link(target);
          out.push('<a href="');
          escapeRange(href, 0, href.length, out);
          out.push('">');
          inlineRange(s, j + 1, k, env, out);
          out.push('</a>');
          i = mm + 1;
        } else {
          out.push('[');
          i = j + 1;
        }
      } else {
        out.push('[');
        i = j + 1;
      }
    } else {
      out.push(c === 38 ? '&amp;' : c === 60 ? '&lt;' : c === 62 ? '&gt;' : c === 34 ? '&quot;' : '&#39;');
      i = j + 1;
    }
    SPECIAL_RE.lastIndex = i;
  }
}

/** `s` rendered inline. */
function inlineStr(s, env) {
  const out = [];
  inlineRange(s, 0, s.length, env, out);
  return out.join('');
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of
 * contents (every level 2 and 3 heading: level, id and its inline HTML) and its excerpt (the
 * first paragraph's inline HTML, or "").
 */
function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const n = lines.length;
  const ids = new Set();
  const toc = [];
  let excerpt = null;
  const out = [];
  let i = 0;
  while (i < n) {
    const line = lines[i];
    const c0 = line.length === 0 ? -1 : line.charCodeAt(0);
    if (c0 === 96) {
      const lang = fenceLang(line);
      if (lang !== null) {
        const body = [];
        i++;
        while (i < n && !isFenceClose(lines[i])) body.push(lines[i++]);
        i++;
        out.push('<pre><code');
        if (lang !== '') {
          out.push(' class="language-');
          escapeRange(lang, 0, lang.length, out);
          out.push('"');
        }
        out.push('>');
        for (const l of body) {
          escapeRange(l, 0, l.length, out);
          out.push('\n');
        }
        out.push('</code></pre>\n');
        continue;
      }
    } else if (c0 === 35) {
      const hd = headingOf(line);
      if (hd !== null) {
        const id = uniqueSlug(slugify(hd.text), ids);
        const html = inlineStr(hd.text, env);
        out.push(`<h${hd.depth} id="${id}">`, html, `</h${hd.depth}>\n`);
        if (hd.depth === 2 || hd.depth === 3) toc.push({ level: hd.depth, id, html });
        i++;
        continue;
      }
    } else if (c0 === 45 || c0 === 42) {
      if (isHr(line)) {
        out.push('<hr>\n');
        i++;
        continue;
      }
      const b = bulletText(line);
      if (b !== null) {
        const items = [];
        while (i < n) {
          const m = bulletText(lines[i]);
          if (m !== null) {
            items.push([trimLine(m)]);
            i++;
          } else if (isContinued(lines[i])) {
            items[items.length - 1].push(trimLine(lines[i]));
            i++;
          } else break;
        }
        out.push('<ul>\n');
        for (const parts of items) {
          out.push('<li>');
          const text = parts.join('\n');
          inlineRange(text, 0, text.length, env, out);
          out.push('</li>\n');
        }
        out.push('</ul>\n');
        continue;
      }
    } else if (c0 === 62) {
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i++];
        l = l.slice(l.charCodeAt(1) === 32 ? 2 : 1);
        l = trimLine(l);
        if (l !== '') body.push(l);
      }
      if (body.length === 0) out.push('<blockquote>\n</blockquote>\n');
      else {
        out.push('<blockquote>\n<p>');
        const text = body.join('\n');
        inlineRange(text, 0, text.length, env, out);
        out.push('</p>\n</blockquote>\n');
      }
      continue;
    } else if (c0 >= 48 && c0 <= 57) {
      const o = orderedItem(line);
      if (o !== null) {
        const start = o.num;
        const items = [];
        while (i < n) {
          const m = orderedItem(lines[i]);
          if (m !== null) {
            items.push([trimLine(m.text)]);
            i++;
          } else if (isContinued(lines[i])) {
            items[items.length - 1].push(trimLine(lines[i]));
            i++;
          } else break;
        }
        if (start !== 1) out.push(`<ol start="${start}">\n`);
        else out.push('<ol>\n');
        for (const parts of items) {
          out.push('<li>');
          const text = parts.join('\n');
          inlineRange(text, 0, text.length, env, out);
          out.push('</li>\n');
        }
        out.push('</ol>\n');
        continue;
      }
    } else if (c0 === -1 || c0 === 32 || c0 === 9) {
      if (isBlank(line)) {
        i++;
        continue;
      }
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const text = body.join('\n');
    if (excerpt === null) {
      excerpt = inlineStr(text, env);
      out.push('<p>', excerpt, '</p>\n');
    } else {
      out.push('<p>');
      inlineRange(text, 0, text.length, env, out);
      out.push('</p>\n');
    }
  }
  return { html: out.join(''), toc, excerpt: excerpt ?? '' };
}

